"""Draws src/img/constellations.svg, the site's background pattern: all 88 constellations as faint stick figures,
scattered over a tile that repeats seamlessly. Figures come from src/data/sky.json (d3-celestial lines).
Run from the repo root:  python3 tools/sky/background.py
Same seed, same picture; change SEED for a different arrangement.
"""
import json, math, os, random

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
SEED, COLS, ROWS, CELL = 7, 6, 15, 300   # a tall tile: the page scrolls through it slowly (see js/skybg.js)
W, H = COLS * CELL, ROWS * CELL

sky = json.load(open(os.path.join(ROOT, 'src', 'data', 'sky.json'), encoding='utf-8'))
mags = {(round(s[0], 1), round(s[1], 1)): s[2] for s in sky['stars']}

def project(lines):
    """Stereographic projection about the figure's center, east to the left as seen from Earth."""
    pts = [p for l in lines for p in l]
    x0 = math.radians(pts[0][0])
    lon = [math.atan2(math.sin(math.radians(p[0]) - x0), math.cos(math.radians(p[0]) - x0)) + x0 for p in pts]
    lam0, phi0 = sum(lon) / len(lon), math.radians(sum(p[1] for p in pts) / len(pts))
    def f(p):
        lam, phi = math.radians(p[0]), math.radians(p[1])
        k = 2 / (1 + math.sin(phi0) * math.sin(phi) + math.cos(phi0) * math.cos(phi) * math.cos(lam - lam0))
        x = k * math.cos(phi) * math.sin(lam - lam0)
        y = k * (math.cos(phi0) * math.sin(phi) - math.sin(phi0) * math.cos(phi) * math.cos(lam - lam0))
        return -x, -y
    return [[f(p) for p in l] for l in lines]

figs = {}
for key, c in sky['con'].items():
    name = 'Serpens' if key.startswith('Ser') else key
    figs.setdefault(name, []).extend(c['l'])
assert len(figs) == 88, len(figs)

rnd = random.Random(SEED)
names = sorted(figs)
rnd.shuffle(names)
cells = [(i % COLS, i // COLS) for i in range(COLS * ROWS)]
rnd.shuffle(cells)

paths, dots = [], []
for name, (cx, cy) in zip(names, cells):
    lines = figs[name]
    proj = project(lines)
    xs = [p[0] for l in proj for p in l]; ys = [p[1] for l in proj for p in l]
    ext = max(max(xs) - min(xs), max(ys) - min(ys)) or 1
    # Big constellations fill most of a cell; small ones stay small, but not tiny.
    size = CELL * min(.7, max(.3, (.3 + ext * 1.1) * .76))
    s = size / ext
    rot = math.radians(rnd.uniform(-25, 25)); cr, sr = math.cos(rot), math.sin(rot)
    mx, my = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    ox = cx * CELL + CELL / 2 + rnd.uniform(-1, 1) * (CELL - size) / 2 * .8
    oy = cy * CELL + CELL / 2 + rnd.uniform(-1, 1) * (CELL - size) / 2 * .8
    def t(p):
        x, y = (p[0] - mx) * s, (p[1] - my) * s
        return ox + x * cr - y * sr, oy + x * sr + y * cr
    d, seen = [], set()
    for l, pl in zip(lines, proj):
        q = [t(p) for p in pl]
        d.append('M' + 'L'.join(f'{x:.0f} {y:.0f}' for x, y in q))
        for (x, y), p in zip(q, l):
            k = (round(x), round(y))
            if k in seen: continue
            seen.add(k)
            m = mags.get((round(p[0], 1), round(p[1], 1)), 4)
            dots.append((x, y, max(.8, 2.3 - .3 * m), max(.18, .5 - .06 * m)))
    paths.append(f'<path d="{" ".join(d)}"><title>{name}</title></path>')

# Scattered faint stars, wrapped so the edges match up.
for _ in range(700):
    dots.append((rnd.uniform(0, W), rnd.uniform(0, H), rnd.choice((.5, .6, .7, .9)), rnd.choice((.08, .12, .16, .22))))

out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">',
       '<!-- Background pattern: all 88 constellations as faint star figures, plus scattered stars. Tiles seamlessly. Generated by tools/sky/background.py. -->',
       '<g fill="none" stroke="#a9c6f0" stroke-opacity=".12" stroke-width="1.1" stroke-linecap="round" stroke-linejoin="round">',
       *paths, '</g><g fill="#dfe7ff">',
       *(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{r:.1f}" fill-opacity="{o:.2f}"/>' for x, y, r, o in dots), '</g></svg>']
open(os.path.join(ROOT, 'src', 'img', 'constellations.svg'), 'w', encoding='utf-8').write('\n'.join(out))
print(f'{len(paths)} constellations, {len(dots)} stars, {W}×{H}')
